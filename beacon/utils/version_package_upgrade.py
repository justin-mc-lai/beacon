"""Cumulative delivery-package upgrades for Beacon version materials."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

from beacon.utils.artifact_paths import machine_execution_dir
from beacon.utils.runtime import now_iso, write_json
from beacon.utils.source_architecture import generate_source_architecture
from beacon.utils.v115_delivery import repair_v115_delivery_package
from beacon.utils.versioning import normalize_version, resolve_target_version


@dataclass(frozen=True)
class _UpgradeStep:
    step: str
    min_version: str
    future_rule: str
    apply_fn: Callable[[Path, str, bool], Any]


def _parse_semver_tuple(value: str | None) -> tuple[int, int, int]:
    normalized = normalize_version(value) or "v0.0.0"
    try:
        major, minor, patch = normalized.lstrip("v").split(".")
        return (int(major), int(minor), int(patch))
    except Exception:  # noqa: BLE001
        return (0, 0, 0)


def _ensure_project_skill_blueprint(project_root: Path, *, version: str, apply: bool) -> dict[str, Any]:
    resolved_version = resolve_target_version(project_root, version)
    path = project_root / "docs" / "beacon" / resolved_version / "execution" / "project-skill-qa-evolution-blueprint.md"
    content = "\n".join(
        [
            "# Project Skill QA Evolution Blueprint",
            "",
            f"- version: `{resolved_version}`",
            "- generated by `beacon doctor upgrade-package`",
            "",
            "This placeholder blueprint keeps older version packages compatible with post-v1.1.10 delivery checks.",
            "",
        ]
    ) + "\n"
    changed = (not path.exists()) or path.read_text(encoding="utf-8") != content if path.exists() else True
    if apply and changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return {
        "path": str(path.relative_to(project_root)),
        "action": "written" if changed and apply else ("planned" if changed else "unchanged"),
    }


def _ensure_release_stub(project_root: Path, *, version: str, apply: bool) -> dict[str, Any]:
    resolved_version = resolve_target_version(project_root, version)
    path = project_root / "docs" / "beacon" / resolved_version / "release" / f"{resolved_version}.md"
    content = "\n".join(
        [
            f"# Release: {resolved_version}",
            "",
            "<!-- version-line stub generated by `beacon doctor upgrade-package`; extend at release stage -->",
            "",
        ]
    )
    changed = (not path.exists()) or path.read_text(encoding="utf-8") != content if path.exists() else True
    if apply and changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return {
        "path": str(path.relative_to(project_root)),
        "action": "written" if changed and apply else ("planned" if changed else "unchanged"),
    }


def _ensure_implementation_plan_support_marker(project_root: Path, *, version: str, apply: bool) -> dict[str, Any]:
    resolved_version = resolve_target_version(project_root, version)
    path = machine_execution_dir(project_root, resolved_version) / "implementation-plan-support.json"
    payload = {
        "schema_version": "1.0",
        "version": resolved_version,
        "supported": True,
        "generated_at": now_iso(),
        "notes": [
            "v1.1.12+ packages support implementation-plan runtime closures",
            "feature-specific implementation plans are generated on demand by `beacon implement plan`",
        ],
    }
    current = None
    if path.exists():
        try:
            current = json.loads(path.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            current = None
    changed = current != payload
    if apply and changed:
        write_json(path, payload)
    return {
        "path": str(path.relative_to(project_root)),
        "action": "written" if changed and apply else ("planned" if changed else "unchanged"),
    }


_UPGRADE_STEP_REGISTRY: tuple[_UpgradeStep, ...] = (
    _UpgradeStep(
        step="v1.1.5-machine-surface",
        min_version="v1.1.5",
        future_rule="Append later version-package upgrade steps after this registry entry; do not rewrite old steps in place.",
        apply_fn=lambda project_root, resolved_version, apply: repair_v115_delivery_package(
            project_root,
            version=resolved_version,
            apply=apply,
        ),
    ),
    _UpgradeStep(
        step="v1.1.10-source-architecture",
        min_version="v1.1.10",
        future_rule="Append later version-package upgrade steps after this registry entry; do not rewrite old steps in place.",
        apply_fn=lambda project_root, resolved_version, apply: {
            "source_architecture": generate_source_architecture(project_root, version=resolved_version)
            if apply
            else {"status": "planned"},
            "project_skill_blueprint": _ensure_project_skill_blueprint(
                project_root,
                version=resolved_version,
                apply=apply,
            ),
        },
    ),
    _UpgradeStep(
        step="v1.1.12-implementation-plan-support",
        min_version="v1.1.12",
        future_rule="Append later version-package upgrade steps after this registry entry; do not rewrite old steps in place.",
        apply_fn=lambda project_root, resolved_version, apply: {
            "support_marker": _ensure_implementation_plan_support_marker(
                project_root,
                version=resolved_version,
                apply=apply,
            ),
        },
    ),
    _UpgradeStep(
        step="v1.1.13-release-stub",
        min_version="v1.1.13",
        future_rule="Append later version-package upgrade steps after this registry entry; do not rewrite old steps in place.",
        apply_fn=lambda project_root, resolved_version, apply: {
            "release_stub": _ensure_release_stub(
                project_root,
                version=resolved_version,
                apply=apply,
            ),
        },
    ),
)


def registered_upgrade_steps() -> list[dict[str, str]]:
    """Expose the append-only upgrade registry for tests and doctor output."""
    return [
        {
            "step": item.step,
            "min_version": item.min_version,
            "future_rule": item.future_rule,
        }
        for item in _UPGRADE_STEP_REGISTRY
    ]


def upgrade_version_package(project_root: Path, *, version: str, apply: bool = True) -> dict[str, Any]:
    """Apply cumulative package upgrades required by later Beacon runtime lines.

    Rule: later version lines must register their package/material upgrade hooks here.
    """

    resolved_version = resolve_target_version(project_root, version)
    current = _parse_semver_tuple(resolved_version)
    steps: list[dict[str, Any]] = []

    def _add_step(name: str, applies: bool, fn: Callable[[], Any]) -> None:
        if not applies:
            return
        result = fn()
        steps.append({"step": name, "result": result})

    for item in _UPGRADE_STEP_REGISTRY:
        _add_step(
            item.step,
            current >= _parse_semver_tuple(item.min_version),
            lambda item=item: item.apply_fn(project_root, resolved_version, apply),
        )

    action_summary = {"written": 0, "planned": 0, "unchanged": 0}
    touched_paths: list[str] = []

    def _collect(node: Any) -> None:
        if isinstance(node, dict):
            action = str(node.get("action", "") or "").strip().lower()
            path = str(node.get("path", "") or "").strip()
            if action in action_summary:
                action_summary[action] += 1
                if path and action in {"written", "planned"}:
                    touched_paths.append(path)
            for value in node.values():
                _collect(value)
        elif isinstance(node, list):
            for item in node:
                _collect(item)

    _collect(steps)

    return {
        "schema_version": "1.0",
        "version": resolved_version,
        "applied": apply,
        "registry": registered_upgrade_steps(),
        "steps": steps,
        "summary": {
            **action_summary,
            "step_count": len(steps),
            "registered_step_count": len(_UPGRADE_STEP_REGISTRY),
            "touched_paths": list(dict.fromkeys(touched_paths)),
        },
        "notes": [
            "Later Beacon version lines must register cumulative package upgrades here.",
            "Keep the doctor upgrade registry append-only so future versions can add new steps without mutating historical upgrade behavior.",
            "Upgrade flow keeps old requirement materials usable with newer runtime features when structurally possible.",
        ],
    }
